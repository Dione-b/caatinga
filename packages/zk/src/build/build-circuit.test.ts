import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { generateVkRust } from "./build-circuit.js";

const fixtureDir = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../test/fixtures");

describe("generateVkRust", () => {
  it("should_emit_embedded_vk_with_g1_and_g2_coordinates_when_given_verification_key_json", () => {
    const rawJson = readFileSync(path.join(fixtureDir, "verification_key.json"), "utf8");
    const rustSource = generateVkRust(".artifacts/zk/main/verification_key.json", rawJson);

    expect(rustSource).toContain("// @generated by ctg zk build --embed-vk");
    expect(rustSource).toContain("pub fn embedded_vk(");
    expect(rustSource).toContain("G1Affine::from_array(&env, &[");
    expect(rustSource).toContain("G2Affine::from_array(&env, &[");
    expect(rustSource).toContain("soroban_sdk::vec![&env,");
    expect(rustSource).toContain("// IC[0]");
    expect(rustSource).not.toContain("todo!");
  });
});
