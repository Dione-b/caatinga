import { readFile, writeFile } from "node:fs/promises";
import { embeddedVkSourcePath } from "../artifacts/zk-paths.js";
import { concatG1Bytes, concatG2Bytes } from "../serialization/curve-bytes.js";
import { serializeVk, type SnarkjsVk } from "../serialization/serialize-vk.js";

/** Marker the scaffold placeholder carries, so a stale vk.rs is detectable. */
const EMBEDDED_VK_PLACEHOLDER_MARKER = "PLACEHOLDER verification key shipped with the scaffold";

const BYTES_PER_LINE = 16;

/** Whether a `vk.rs` source is still the scaffold placeholder, which panics on purpose. */
export function isPlaceholderEmbeddedVk(source: string): boolean {
  return source.includes(EMBEDDED_VK_PLACEHOLDER_MARKER);
}

function formatRustByteArray(bytes: Uint8Array): string {
  const chunks: string[] = [];
  for (let i = 0; i < bytes.length; i += BYTES_PER_LINE) {
    const slice = Array.from(bytes.slice(i, i + BYTES_PER_LINE));
    chunks.push(
      "        " + slice.map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") + ","
    );
  }
  return chunks.join("\n");
}

/** Rust source of `vk.rs` for a snarkjs verification key given as JSON text. */
export function generateVkRust(rawJson: string): string {
  const vk = serializeVk(JSON.parse(rawJson) as SnarkjsVk);

  const icItems = vk.ic
    .map(concatG1Bytes)
    .map(
      (ic, i) =>
        `        G1Affine::from_array(&env, &[\n${formatRustByteArray(ic)}\n        ]), // IC[${i}]`
    )
    .join("\n");

  return [
    "// @generated by ctg zk build --embed-vk",
    `// DO NOT EDIT — re-run "ctg zk build <circuit> --embed-vk" to regenerate.`,
    "",
    "use soroban_sdk::crypto::bls12_381::{Bls12381G1Affine as G1Affine, Bls12381G2Affine as G2Affine};",
    "",
    "#[allow(clippy::too_many_lines)]",
    "pub fn embedded_vk(",
    "    env: &soroban_sdk::Env,",
    ") -> (G1Affine, G2Affine, G2Affine, G2Affine, soroban_sdk::Vec<G1Affine>) {",
    `    let alpha = G1Affine::from_array(&env, &[`,
    formatRustByteArray(concatG1Bytes(vk.alpha)),
    "    ]);",
    `    let beta = G2Affine::from_array(&env, &[`,
    formatRustByteArray(concatG2Bytes(vk.beta)),
    "    ]);",
    `    let gamma = G2Affine::from_array(&env, &[`,
    formatRustByteArray(concatG2Bytes(vk.gamma)),
    "    ]);",
    `    let delta = G2Affine::from_array(&env, &[`,
    formatRustByteArray(concatG2Bytes(vk.delta)),
    "    ]);",
    `    let ic = soroban_sdk::vec![&env,`,
    icItems,
    "    ];",
    "    (alpha, beta, gamma, delta, ic)",
    "}",
    "",
  ].join("\n");
}

/** Writes `vk.rs` into the verifier contract from a `verification_key.json`. */
export async function writeEmbeddedVk(vkPath: string, cwd?: string): Promise<void> {
  const rustSource = generateVkRust(await readFile(vkPath, "utf8"));
  await writeFile(embeddedVkSourcePath(cwd), rustSource, "utf8");
}
