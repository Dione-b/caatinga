import { runCommand } from "@caatinga/core";
import path from "node:path";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createHash, randomBytes } from "node:crypto";
import { ensureCircom, ensurePtau, ensureSnarkjs } from "../install/lazy-install-zk-tools.js";
import type { ZkInstallProgress } from "../install/install-progress.js";
import { ptauSizeForConstraints } from "./detect-ptau-size.js";
import { writeDevCeremonyManifest } from "../ceremony/dev-ceremony.js";
import { serializeVk, type SnarkjsVk } from "../serialization/serialize-vk.js";
import { concatG1Bytes, concatG2Bytes } from "../serialization/curve-bytes.js";

export type BuildCircuitOptions = {
  circuitName: string;
  circuitPath: string;
  artifactsDir: string;
  embedVk: boolean;
  progress?: ZkInstallProgress;
};

const BYTES_PER_LINE = 16;

function formatRustByteArray(bytes: Uint8Array): string {
  const chunks: string[] = [];
  for (let i = 0; i < bytes.length; i += BYTES_PER_LINE) {
    const slice = Array.from(bytes.slice(i, i + BYTES_PER_LINE));
    chunks.push(
      "        " + slice.map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") + ","
    );
  }
  return chunks.join("\n");
}

export function generateVkRust(_vkPath: string, rawJson: string): string {
  const raw = JSON.parse(rawJson) as SnarkjsVk;
  const vk = serializeVk(raw);

  const alphaBytes = concatG1Bytes(vk.alpha);
  const betaBytes = concatG2Bytes(vk.beta);
  const gammaBytes = concatG2Bytes(vk.gamma);
  const deltaBytes = concatG2Bytes(vk.delta);
  const icEntries = vk.ic.map(concatG1Bytes);

  const icItems = icEntries
    .map(
      (ic, i) =>
        `        G1Affine::from_array(&env, &[\n${formatRustByteArray(ic)}\n        ]), // IC[${i}]`
    )
    .join("\n");

  return [
    "// @generated by ctg zk build --embed-vk",
    `// DO NOT EDIT — re-run "ctg zk build <circuit> --embed-vk" to regenerate.`,
    "",
    "use soroban_sdk::crypto::bls12_381::{G1Affine, G2Affine};",
    "",
    "#[allow(clippy::too_many_lines)]",
    "pub fn embedded_vk(",
    "    env: &soroban_sdk::Env,",
    ") -> (G1Affine, G2Affine, G2Affine, G2Affine, soroban_sdk::Vec<G1Affine>) {",
    `    let alpha = G1Affine::from_array(&env, &[`,
    formatRustByteArray(alphaBytes),
    "    ]);",
    `    let beta = G2Affine::from_array(&env, &[`,
    formatRustByteArray(betaBytes),
    "    ]);",
    `    let gamma = G2Affine::from_array(&env, &[`,
    formatRustByteArray(gammaBytes),
    "    ]);",
    `    let delta = G2Affine::from_array(&env, &[`,
    formatRustByteArray(deltaBytes),
    "    ]);",
    `    let ic = soroban_sdk::vec![&env,`,
    icItems,
    "    ];",
    "    (alpha, beta, gamma, delta, ic)",
    "}",
    "",
  ].join("\n");
}

async function writeEmbeddedVk(vkPath: string, verifierSrcDir: string): Promise<void> {
  const rawJson = await readFile(vkPath, "utf8");
  const rustSource = generateVkRust(vkPath, rawJson);
  await writeFile(path.join(verifierSrcDir, "vk.rs"), rustSource, "utf8");
}

export async function buildCircuit(options: BuildCircuitOptions): Promise<void> {
  const progress = options.progress;
  const circom = await ensureCircom(progress);
  const snarkjs = await ensureSnarkjs(progress);
  const circuitDir = path.resolve(options.circuitPath);
  const outDir = path.resolve(options.artifactsDir);
  const circuitFile = path.join(circuitDir, "main.circom");
  const r1csPath = path.join(outDir, "main.r1cs");
  const zkey0 = path.join(outDir, "circuit_0000.zkey");
  const zkeyFinal = path.join(outDir, "circuit_final.zkey");
  const vkPath = path.join(outDir, "verification_key.json");

  await mkdir(outDir, { recursive: true });

  progress?.onStatus?.(`Compiling ${circuitFile}...`);
  await runCommand(circom, [
    circuitFile,
    "--r1cs",
    "--wasm",
    "--sym",
    "-p",
    "bls12381",
    "-o",
    outDir,
  ]);

  const r1csInfo = await runCommand(snarkjs, ["r1cs", "info", r1csPath]);
  const constraintMatch = r1csInfo.stdout.match(/# of Constraints:\s+(\d+)/);
  const constraints = constraintMatch ? Number.parseInt(constraintMatch[1]!, 10) : 1;
  const ptauSize = ptauSizeForConstraints(constraints);
  const ptauPath = await ensurePtau(ptauSize, progress);
  const entropy = createHash("sha256").update(randomBytes(32)).digest("hex");

  progress?.onStatus?.("Running Groth16 trusted setup...");
  await runCommand(snarkjs, ["groth16", "setup", r1csPath, ptauPath, zkey0]);
  await runCommand(snarkjs, ["zkey", "contribute", zkey0, zkeyFinal, "-v"], {
    input: `caatinga-dev\n${entropy}\n`,
  });
  await runCommand(snarkjs, ["zkey", "export", "verificationkey", zkeyFinal, vkPath]);

  if (options.embedVk) {
    const verifierSrcDir = path.resolve("contracts", "verifier", "src");
    await writeEmbeddedVk(vkPath, verifierSrcDir);
  }

  await writeDevCeremonyManifest(outDir);
}
